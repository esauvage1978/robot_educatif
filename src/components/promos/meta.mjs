export function langueDe(pathname) {
  const geo = String(pathname).match(/^\/(uk|ca|en|de|it|es|nl)(\/|$)/)?.[1] || 'fr';
  return { geo, lang: geo === 'uk' || geo === 'ca' ? 'en' : geo };
}

export function urlsDe(geo) {
  return URLS[geo] || URLS.fr;
}

export function metaPage(pathname, explication) {
  const { lang } = langueDe(pathname);
  const T = TEXTES[lang] || TEXTES.fr;
  return {
    titre: explication ? T.titreExplication : T.titre,
    description: explication ? T.descExplication : T.desc,
  };
}

