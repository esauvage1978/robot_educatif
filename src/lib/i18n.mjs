function fusionnerPaires(paires, ajouts) {
	const out = paires.map((p) => ({ ...p }));
	for (const a of ajouts) {
		const p = out.find((x) => Object.entries(a).some(([k, v]) => v && x[k] === v));
		if (!p) out.push({ ...a });
		else for (const [k, v] of Object.entries(a)) if (!p[k]) p[k] = v;
	}
	return out;
}

